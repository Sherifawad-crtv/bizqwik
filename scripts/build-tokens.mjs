// Turns the master token file (src/design-system/tokens/tokens.json, W3C
// Design Tokens Format) into the two files the app reads:
//   tokens.css  every token as a CSS variable (--color-bg-canvas-default …)
//   tokens.ts   the same values as TypeScript constants, for code that needs
//               numbers (motion durations, radii in maths, …)
// Run: npm run tokens   ·   npm run tokens -- --check  (fails if out of date)
import StyleDictionary from "style-dictionary";
import { readFileSync } from "node:fs";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const DIR = "src/design-system/tokens";
const check = process.argv.includes("--check");
const outDir = check ? mkdtempSync(join(tmpdir(), "tokens-")) + "/" : `${DIR}/`;

const HEADER = "Generated by scripts/build-tokens.mjs from tokens.json. Do not edit; edit tokens.json and run `npm run tokens`.";

// TypeScript: one flat object, camelCase keys, numbers where the value is a
// plain px / ms amount so code can do maths with it.
StyleDictionary.registerFormat({
  name: "bizqwik/ts",
  format: ({ dictionary }) => {
    const camel = (path) =>
      path
        .join("-")
        .replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
    const lines = dictionary.allTokens
      .filter((t) => t.path[0] !== "primitive")
      .map((t) => {
        let v = t.$value ?? t.value;
        if (typeof v === "string" && /^-?\d+(\.\d+)?(px|ms)$/.test(v)) v = parseFloat(v);
        return `  ${camel(t.path)}: ${JSON.stringify(v)},`;
      });
    return `// ${HEADER}\nexport const tokens = {\n${lines.join("\n")}\n} as const;\n`;
  },
});

const sd = new StyleDictionary({
  source: [`${DIR}/tokens.json`],
  usesDtcg: true,
  log: { verbosity: "silent", warnings: "disabled" },
  platforms: {
    css: {
      transformGroup: "css",
      buildPath: outDir,
      files: [
        {
          destination: "tokens.css",
          format: "css/variables",
          // Semantic tokens point at primitives (var(--…)), so the theme can
          // swap the brand primitives at runtime and everything follows.
          options: { outputReferences: true, fileHeader: () => [HEADER] },
        },
      ],
    },
    ts: {
      transformGroup: "js",
      transforms: ["attribute/cti", "name/camel", "cubicBezier/css", "shadow/css/shorthand", "fontFamily/css"],
      buildPath: outDir,
      files: [{ destination: "tokens.ts", format: "bizqwik/ts" }],
    },
  },
});

await sd.buildAllPlatforms();

if (check) {
  let stale = false;
  for (const f of ["tokens.css", "tokens.ts"]) {
    if (readFileSync(outDir + f, "utf8") !== readFileSync(`${DIR}/${f}`, "utf8")) {
      console.error(`✗ ${DIR}/${f} is out of date with tokens.json. Run: npm run tokens`);
      stale = true;
    }
  }
  rmSync(outDir, { recursive: true, force: true });
  if (stale) process.exit(1);
  console.log("✓ tokens.css and tokens.ts match tokens.json");
}
